-- JobAI v1.0 — 17-table initial release schema
-- Run in pgAdmin Query Tool while connected to jobai_db.
-- This script is transactional and safe to rerun (existing tables are not replaced).
BEGIN;
CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE SCHEMA IF NOT EXISTS jobai;

CREATE TABLE IF NOT EXISTS jobai.users (
 id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
 auth_user_id UUID UNIQUE, -- populate when integrating Supabase Auth
 email VARCHAR(320) NOT NULL,
 account_status VARCHAR(20) NOT NULL DEFAULT 'active' CHECK (account_status IN ('pending','active','suspended','deleted')),
 onboarding_status VARCHAR(20) NOT NULL DEFAULT 'not_started' CHECK (onboarding_status IN ('not_started','in_progress','completed')),
 onboarding_step SMALLINT NOT NULL DEFAULT 0 CHECK (onboarding_step BETWEEN 0 AND 6),
 email_verified_at TIMESTAMPTZ,
 last_login_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 deleted_at TIMESTAMPTZ,
 CONSTRAINT users_email_nonempty CHECK (length(trim(email)) > 3)
);
CREATE UNIQUE INDEX IF NOT EXISTS users_email_ci_uq ON jobai.users (lower(email));

CREATE TABLE IF NOT EXISTS jobai.user_profiles (
 user_id UUID PRIMARY KEY REFERENCES jobai.users(id) ON DELETE CASCADE,
 first_name VARCHAR(100) NOT NULL,
 middle_name VARCHAR(100), last_name VARCHAR(100), preferred_name VARCHAR(100),
 phone_country_code VARCHAR(8), phone_number VARCHAR(30), date_of_birth DATE,
 address_line_1 VARCHAR(200), address_line_2 VARCHAR(200),
 city VARCHAR(120), state_province VARCHAR(120), country_code CHAR(2), postal_code VARCHAR(20),
 professional_headline VARCHAR(250), professional_summary TEXT,
 linkedin_url TEXT, github_url TEXT, portfolio_url TEXT, profile_photo_path TEXT,
 timezone VARCHAR(64),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CONSTRAINT user_profiles_first_name_nonempty CHECK (length(trim(first_name)) > 0)
);

CREATE TABLE IF NOT EXISTS jobai.education_levels (
 id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code VARCHAR(40) NOT NULL UNIQUE, display_name VARCHAR(100) NOT NULL,
 sort_order SMALLINT NOT NULL DEFAULT 0, is_active BOOLEAN NOT NULL DEFAULT true
);
INSERT INTO jobai.education_levels(code,display_name,sort_order) VALUES
