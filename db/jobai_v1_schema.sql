CREATE TABLE IF NOT EXISTS jobai.user_education (
 id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
 user_id UUID NOT NULL REFERENCES jobai.users(id) ON DELETE CASCADE,
 education_level_id SMALLINT NOT NULL REFERENCES jobai.education_levels(id),
 degree_name VARCHAR(200) NOT NULL, field_of_study VARCHAR(200), specialization VARCHAR(200),
 institution_name VARCHAR(250) NOT NULL, campus_name VARCHAR(200),
 institution_city VARCHAR(120), institution_state VARCHAR(120), institution_country CHAR(2),
 start_date DATE, end_date DATE, expected_graduation_date DATE, graduation_year SMALLINT,
 is_currently_studying BOOLEAN NOT NULL DEFAULT false,
 education_status VARCHAR(20) NOT NULL DEFAULT 'completed' CHECK (education_status IN ('pursuing','completed','discontinued')),
 grade_type VARCHAR(20) CHECK (grade_type IN ('gpa','cgpa','percentage','other')),
 grade_value NUMERIC(6,3), grade_maximum NUMERIC(6,3),
 honors_awards TEXT, activities TEXT, description TEXT,
 display_order SMALLINT NOT NULL DEFAULT 0,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK (end_date IS NULL OR start_date IS NULL OR end_date >= start_date),
 CHECK (grade_value IS NULL OR grade_value >= 0),
 CHECK (grade_maximum IS NULL OR grade_maximum > 0),
 CHECK (grade_value IS NULL OR grade_maximum IS NULL OR grade_value <= grade_maximum),
 CHECK (graduation_year IS NULL OR graduation_year BETWEEN 1900 AND 2200),
 CHECK (NOT is_currently_studying OR end_date IS NULL),
 CHECK (NOT is_currently_studying OR education_status = 'pursuing')
);
CREATE INDEX IF NOT EXISTS user_education_user_idx ON jobai.user_education(user_id,display_order);

CREATE TABLE IF NOT EXISTS jobai.user_experience (
 id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
 user_id UUID NOT NULL REFERENCES jobai.users(id) ON DELETE CASCADE,
 company_name VARCHAR(250) NOT NULL, company_website TEXT, job_title VARCHAR(200) NOT NULL,
 employment_type VARCHAR(30), work_arrangement VARCHAR(20),
 location_city VARCHAR(120), location_state VARCHAR(120), location_country CHAR(2),
 start_date DATE NOT NULL, end_date DATE, is_current BOOLEAN NOT NULL DEFAULT false,
 description TEXT, achievements TEXT, technologies_used JSONB NOT NULL DEFAULT '[]'::jsonb,
 industry VARCHAR(120), display_order SMALLINT NOT NULL DEFAULT 0,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK (end_date IS NULL OR end_date >= start_date),
 CHECK (NOT is_current OR end_date IS NULL),
 CHECK (jsonb_typeof(technologies_used) = 'array')
);
CREATE INDEX IF NOT EXISTS user_experience_user_idx ON jobai.user_experience(user_id,start_date DESC);

CREATE TABLE IF NOT EXISTS jobai.skills (
 id UUID PRIMARY KEY DEFAULT gen_random_uuid(), canonical_name VARCHAR(150) NOT NULL,
 category VARCHAR(80), description TEXT, is_active BOOLEAN NOT NULL DEFAULT true,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS skills_name_ci_uq ON jobai.skills(lower(canonical_name));

CREATE TABLE IF NOT EXISTS jobai.user_skills (
 id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
 user_id UUID NOT NULL REFERENCES jobai.users(id) ON DELETE CASCADE,
 skill_id UUID NOT NULL REFERENCES jobai.skills(id),
 proficiency_level VARCHAR(20) CHECK (proficiency_level IN ('beginner','intermediate','advanced','expert')),
 years_experience NUMERIC(4,1), last_used_year SMALLINT,
 is_primary_skill BOOLEAN NOT NULL DEFAULT false,
 source VARCHAR(30) NOT NULL DEFAULT 'manual' CHECK (source IN ('manual','resume','imported')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(user_id,skill_id), CHECK (years_experience IS NULL OR years_experience BETWEEN 0 AND 99)
);
CREATE INDEX IF NOT EXISTS user_skills_skill_idx ON jobai.user_skills(skill_id);

CREATE TABLE IF NOT EXISTS jobai.job_preferences (
 user_id UUID PRIMARY KEY REFERENCES jobai.users(id) ON DELETE CASCADE,
 preferred_job_titles JSONB NOT NULL DEFAULT '[]'::jsonb,
 preferred_locations JSONB NOT NULL DEFAULT '[]'::jsonb,
 preferred_work_types JSONB NOT NULL DEFAULT '[]'::jsonb,
 preferred_employment_types JSONB NOT NULL DEFAULT '[]'::jsonb,
 minimum_salary NUMERIC(14,2), maximum_salary NUMERIC(14,2),
 salary_currency CHAR(3), salary_period VARCHAR(20),
 notice_period_days INTEGER, available_from DATE,
 willing_to_relocate BOOLEAN, requires_visa_sponsorship BOOLEAN,
 minimum_match_score NUMERIC(5,2) NOT NULL DEFAULT 60,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK (jsonb_typeof(preferred_job_titles)='array'),
 CHECK (jsonb_typeof(preferred_locations)='array'),
 CHECK (jsonb_typeof(preferred_work_types)='array'),
 CHECK (jsonb_typeof(preferred_employment_types)='array'),
 CHECK (minimum_salary IS NULL OR minimum_salary >= 0),
 CHECK (maximum_salary IS NULL OR maximum_salary >= 0),
 CHECK (minimum_salary IS NULL OR maximum_salary IS NULL OR minimum_salary <= maximum_salary),
 CHECK ((minimum_salary IS NULL AND maximum_salary IS NULL) OR (salary_currency IS NOT NULL AND salary_period IS NOT NULL)),
 CHECK (notice_period_days IS NULL OR notice_period_days >= 0),
 CHECK (minimum_match_score BETWEEN 0 AND 100)
);

CREATE TABLE IF NOT EXISTS jobai.resumes (
 id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
 user_id UUID NOT NULL REFERENCES jobai.users(id) ON DELETE CASCADE,
 file_name VARCHAR(255) NOT NULL, mime_type VARCHAR(100) NOT NULL,
 file_size_bytes BIGINT NOT NULL CHECK (file_size_bytes > 0),
 storage_bucket VARCHAR(100) NOT NULL, storage_path TEXT NOT NULL,
 file_sha256 CHAR(64), resume_title VARCHAR(150),
 resume_version INTEGER NOT NULL DEFAULT 1 CHECK (resume_version > 0),
 is_primary BOOLEAN NOT NULL DEFAULT false,
 parsing_status VARCHAR(30) NOT NULL DEFAULT 'pending' CHECK (parsing_status IN ('pending','processing','completed','failed')),
 parsed_text TEXT, parsed_data JSONB, parser_version VARCHAR(50), parsed_at TIMESTAMPTZ,
 uploaded_at TIMESTAMPTZ NOT NULL DEFAULT now(), deleted_at TIMESTAMPTZ,
 UNIQUE(user_id,storage_path)
);
CREATE INDEX IF NOT EXISTS resumes_user_idx ON jobai.resumes(user_id,uploaded_at DESC);
CREATE UNIQUE INDEX IF NOT EXISTS resumes_one_primary_per_user_idx ON jobai.resumes(user_id) WHERE is_primary AND deleted_at IS NULL;

CREATE TABLE IF NOT EXISTS jobai.job_sources (
 id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
 source_name VARCHAR(100) NOT NULL UNIQUE,
 source_type VARCHAR(30) NOT NULL CHECK (source_type IN ('api','feed','manual')),
 base_url TEXT, is_active BOOLEAN NOT NULL DEFAULT true,
 rate_limit_per_hour INTEGER CHECK (rate_limit_per_hour IS NULL OR rate_limit_per_hour > 0),
 last_successful_sync_at TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS jobai.companies (
 id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
 company_name VARCHAR(250) NOT NULL, normalized_name VARCHAR(250) NOT NULL,
 website_url TEXT, careers_url TEXT, logo_url TEXT, industry VARCHAR(120),
 company_size VARCHAR(50), headquarters_country CHAR(2), description TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS companies_normalized_name_idx ON jobai.companies(normalized_name);

CREATE TABLE IF NOT EXISTS jobai.job_listings (
 id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
 source_id UUID NOT NULL REFERENCES jobai.job_sources(id),
 company_id UUID REFERENCES jobai.companies(id),
 external_job_id VARCHAR(255) NOT NULL,
 job_title VARCHAR(250) NOT NULL, job_description TEXT NOT NULL,
 responsibilities TEXT, required_qualifications TEXT, preferred_qualifications TEXT,
 minimum_experience_years NUMERIC(4,1), maximum_experience_years NUMERIC(4,1),
 employment_type VARCHAR(30), work_arrangement VARCHAR(20),
 city VARCHAR(120), state_province VARCHAR(120), country_code CHAR(2),
 salary_minimum NUMERIC(14,2), salary_maximum NUMERIC(14,2),
 salary_currency CHAR(3), salary_period VARCHAR(20),
 visa_sponsorship_available BOOLEAN, application_url TEXT NOT NULL,
 posted_at TIMESTAMPTZ, first_seen_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 last_seen_at TIMESTAMPTZ NOT NULL DEFAULT now(), expires_at TIMESTAMPTZ,
 job_status VARCHAR(20) NOT NULL DEFAULT 'active' CHECK (job_status IN ('active','expired','closed')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(source_id,external_job_id),
 CHECK (minimum_experience_years IS NULL OR minimum_experience_years >= 0),
 CHECK (maximum_experience_years IS NULL OR maximum_experience_years >= 0),
 CHECK (minimum_experience_years IS NULL OR maximum_experience_years IS NULL OR minimum_experience_years <= maximum_experience_years),
 CHECK (salary_minimum IS NULL OR salary_minimum >= 0),
 CHECK (salary_maximum IS NULL OR salary_maximum >= 0),
 CHECK (salary_minimum IS NULL OR salary_maximum IS NULL OR salary_minimum <= salary_maximum),
 CHECK ((salary_minimum IS NULL AND salary_maximum IS NULL) OR (salary_currency IS NOT NULL AND salary_period IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS job_listings_recent_idx ON jobai.job_listings(job_status,posted_at DESC);
CREATE INDEX IF NOT EXISTS job_listings_company_idx ON jobai.job_listings(company_id);

CREATE TABLE IF NOT EXISTS jobai.job_matches (
 id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
 user_id UUID NOT NULL REFERENCES jobai.users(id) ON DELETE CASCADE,
 job_id UUID NOT NULL REFERENCES jobai.job_listings(id) ON DELETE CASCADE,
 resume_id UUID REFERENCES jobai.resumes(id) ON DELETE SET NULL,
 overall_match_score NUMERIC(5,2) NOT NULL CHECK (overall_match_score BETWEEN 0 AND 100),
 skills_match_score NUMERIC(5,2) CHECK (skills_match_score BETWEEN 0 AND 100),
 experience_match_score NUMERIC(5,2) CHECK (experience_match_score BETWEEN 0 AND 100),
 education_match_score NUMERIC(5,2) CHECK (education_match_score BETWEEN 0 AND 100),
 location_match_score NUMERIC(5,2) CHECK (location_match_score BETWEEN 0 AND 100),
 matched_skills JSONB, missing_skills JSONB, match_explanation TEXT,
 matching_method VARCHAR(40) NOT NULL DEFAULT 'hybrid' CHECK (matching_method IN ('rules','ai','hybrid')),
 model_name VARCHAR(100), matching_version VARCHAR(30) NOT NULL DEFAULT 'v1',
 calculated_at TIMESTAMPTZ NOT NULL DEFAULT now(), expires_at TIMESTAMPTZ,
 UNIQUE(user_id,job_id)
);
CREATE INDEX IF NOT EXISTS job_matches_user_score_idx ON jobai.job_matches(user_id,overall_match_score DESC);
CREATE INDEX IF NOT EXISTS job_matches_job_idx ON jobai.job_matches(job_id);

CREATE TABLE IF NOT EXISTS jobai.saved_jobs (
 user_id UUID NOT NULL REFERENCES jobai.users(id) ON DELETE CASCADE,
 job_id UUID NOT NULL REFERENCES jobai.job_listings(id) ON DELETE CASCADE,
 saved_at TIMESTAMPTZ NOT NULL DEFAULT now(), notes TEXT,
 PRIMARY KEY(user_id,job_id)
);
CREATE INDEX IF NOT EXISTS saved_jobs_job_idx ON jobai.saved_jobs(job_id);

CREATE TABLE IF NOT EXISTS jobai.job_applications (
 id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
 user_id UUID NOT NULL REFERENCES jobai.users(id) ON DELETE CASCADE,
 job_id UUID REFERENCES jobai.job_listings(id) ON DELETE SET NULL,
 company_name_snapshot VARCHAR(250) NOT NULL,
 job_title_snapshot VARCHAR(250) NOT NULL,
 application_url TEXT,
 application_method VARCHAR(30) NOT NULL DEFAULT 'manual' CHECK (application_method IN ('manual','assisted','automated')),
 application_status VARCHAR(30) NOT NULL DEFAULT 'saved' CHECK (application_status IN ('saved','applied','viewed','shortlisted','interview','offer','rejected','withdrawn','no_response')),
 applied_at TIMESTAMPTZ,
 resume_id UUID REFERENCES jobai.resumes(id) ON DELETE SET NULL,
 cover_letter_path TEXT, recruiter_name VARCHAR(150), recruiter_email VARCHAR(320),
 referral_name VARCHAR(150), notes TEXT,
 last_status_changed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK (application_status='saved' OR applied_at IS NOT NULL)
);
CREATE INDEX IF NOT EXISTS job_applications_user_status_idx ON jobai.job_applications(user_id,application_status);
CREATE INDEX IF NOT EXISTS job_applications_job_idx ON jobai.job_applications(job_id);

CREATE TABLE IF NOT EXISTS jobai.application_events (
 id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
 application_id UUID NOT NULL REFERENCES jobai.job_applications(id) ON DELETE CASCADE,
 old_status VARCHAR(30), new_status VARCHAR(30) NOT NULL,
 reason TEXT, created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS application_events_application_idx ON jobai.application_events(application_id,created_at DESC);

CREATE TABLE IF NOT EXISTS jobai.ai_usage (
 id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
 user_id UUID NOT NULL REFERENCES jobai.users(id) ON DELETE CASCADE,
 model_name VARCHAR(100) NOT NULL, request_type VARCHAR(40) NOT NULL,
 input_tokens INTEGER CHECK (input_tokens IS NULL OR input_tokens >= 0),
 output_tokens INTEGER CHECK (output_tokens IS NULL OR output_tokens >= 0),
 estimated_cost NUMERIC(12,6) CHECK (estimated_cost IS NULL OR estimated_cost >= 0),
 request_status VARCHAR(20) NOT NULL DEFAULT 'success' CHECK (request_status IN ('success','error','rate_limited')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ai_usage_user_time_idx ON jobai.ai_usage(user_id,created_at DESC);

-- Automatically maintain updated_at on updates.
CREATE OR REPLACE FUNCTION jobai.touch_updated_at() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN NEW.updated_at = now(); RETURN NEW; END; $$;
DO $$ DECLARE tab TEXT; BEGIN
 FOREACH tab IN ARRAY ARRAY['users','user_profiles','user_education','user_experience','job_preferences','resumes','job_listings','job_applications'] LOOP
  IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'touch_updated_at_' || tab AND tgrelid = ('jobai.' || tab)::regclass) THEN
   EXECUTE format('CREATE TRIGGER %I BEFORE UPDATE ON jobai.%I FOR EACH ROW EXECUTE FUNCTION jobai.touch_updated_at()', 'touch_updated_at_' || tab,tab);
  END IF;
 END LOOP;
END $$;

-- The backend must authenticate every request and enforce row ownership.
-- RLS policies must be configured before granting direct client-side access.
-- Cross-user resume references (e.g. job_matches.resume_id) also require backend ownership validation.
COMMIT;

